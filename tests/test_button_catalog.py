def png_with_extra_chunk(path, rgba, w, h):
    """The same pixels, other bytes: an ancillary tEXt chunk is inserted before IDAT."""
    image.write_png(path, rgba, w, h)
    data = Path(path).read_bytes()
    body = b"Comment\0same pixels, other file"
    chunk = struct.pack(">I", len(body)) + b"tEXt" + body + struct.pack(">I", zlib.crc32(b"tEXt" + body) & 0xFFFFFFFF)
    i = data.index(b"IDAT") - 4
    Path(path).write_bytes(data[:i] + chunk + data[i:])


def copy_repo_inputs(dst):
    """The files the builder reads, copied to a temp root (art, pages, sources, generated outputs)."""
    for rel in (bc.MASKS, bc.SVG_DIR, "docs/games", "catalog"):
        shutil.copytree(ROOT / rel, Path(dst) / rel)
    shutil.copy(ROOT / bc.DOC_OUT, Path(dst) / bc.DOC_OUT)


class CatalogInSyncTests(unittest.TestCase):
    def test_generated_files_are_up_to_date(self):
        stale = [str(p.relative_to(ROOT)) for p, content in bc.targets(ROOT)
                 if not p.exists() or p.read_text() != content]
        self.assertEqual(stale, [], "run: python3 tools/build_button_catalog.py build")

    def test_check_command_passes(self):
        err = io.StringIO()
        with contextlib.redirect_stderr(err):
            self.assertEqual(bc.main(["build", "--check"]), 0, err.getvalue())
            self.assertEqual(bc.main(["--check"]), 0, err.getvalue())

    def test_generated_header(self):
        text = (ROOT / bc.JSON_OUT).read_text()
        self.assertTrue(text.startswith('{\n "_generated": "GENERATED by tools/build_button_catalog.py - do not edit'))
        doc = (ROOT / bc.DOC_OUT).read_text()
        self.assertIn("GENERATED by tools/build_button_catalog.py - do not edit", doc.splitlines()[0])

    def test_output_is_deterministic(self):
        a = [c for _, c in bc.targets(ROOT)]
        b = [c for _, c in bc.targets(ROOT)]
        self.assertEqual(a, b)
        self.assertEqual(json.loads(a[0]), CATALOG)

    def test_stale_output_is_reported_with_a_diff(self):
        with tempfile.TemporaryDirectory() as tmp:
            copy_repo_inputs(tmp)
            out = Path(tmp) / bc.JSON_OUT
            out.write_text(out.read_text().replace('"schema": 1', '"schema": 2', 1))
            err = io.StringIO()
            with contextlib.redirect_stderr(err):
                self.assertEqual(bc.check(Path(tmp)), 1)
            self.assertIn("out of date: catalog/catalog.json", err.getvalue())
            self.assertIn("run: python3 tools/build_button_catalog.py build", err.getvalue())
            self.assertRegex(err.getvalue(), r"(?m)^  [-+]")

    def test_new_art_fails_until_the_catalog_is_rebuilt(self):
        with tempfile.TemporaryDirectory() as tmp:
            copy_repo_inputs(tmp)
            new = Path(tmp) / bc.MASKS / "new_icon.png"
            image.write_png(str(new), bytes([255, 255, 255, 255]) * 4, 2, 2)
            with self.assertRaises(bc.CatalogError) as cm:      # no profile uses it and art_roles does not know it
                bc.targets(Path(tmp))
            self.assertIn("new_icon.png", str(cm.exception))
            sources = json.loads((Path(tmp) / bc.SOURCES).read_text())
            sources["art_roles"]["%s/new_icon.png" % bc.MASKS] = "home"
            (Path(tmp) / bc.SOURCES).write_text(json.dumps(sources))
            err = io.StringIO()
            with contextlib.redirect_stderr(err):
                self.assertEqual(bc.check(Path(tmp)), 2)         # both generated files are stale now
            for path, content in bc.targets(Path(tmp)):
                path.write_text(content)
            with contextlib.redirect_stderr(err):
                self.assertEqual(bc.check(Path(tmp)), 0)
            cat = json.loads((Path(tmp) / bc.JSON_OUT).read_text())
            self.assertIn("py_modules/button_glyphs/masks/new_icon.png", [v["file"] for v in cat["variants"]])


class CatalogContentTests(unittest.TestCase):
    def test_every_file_exists_and_every_art_file_is_catalogued(self):
        listed = set()
        for v in CATALOG["variants"]:
            for f in [v["file"]] + v.get("same_pixels_as", []):
                self.assertTrue((ROOT / f).is_file(), f)
                listed.add(f)
        self.assertEqual(sorted(set(bc.scan_art(ROOT)) - listed), [], "art not catalogued: run build")
        self.assertEqual(sorted(listed - set(bc.scan_art(ROOT))), [])
        self.assertTrue(any(f.startswith("py_modules/button_glyphs/masks/sfh/") for f in listed))
        self.assertEqual(sum(1 for f in listed if f.endswith(".svg")),
                         len(list((ROOT / bc.SVG_DIR).rglob("*.svg"))))

    def test_nothing_points_outside_our_art_folders(self):
        for v in CATALOG["variants"]:
            for f in [v["file"]] + v.get("same_pixels_as", []):
                self.assertTrue(f.startswith(bc.MASKS + "/") or f.startswith(bc.SVG_DIR + "/"), f)
                self.assertNotIn("..", f)
                self.assertFalse(f.startswith("/"))
        text = (ROOT / bc.JSON_OUT).read_text() + (ROOT / bc.DOC_OUT).read_text()
        for bad in ("/private/tmp", "scratchpad", "steamapps", "/home/deck", "/Users/"):
            self.assertNotIn(bad, text)
        # the catalog stores no pixels: the biggest field is a hash or a sentence, never data
        for v in CATALOG["variants"]:
            self.assertEqual(len(v["sha256"]), 64)
            self.assertLess(len(json.dumps(v)), 2000)

    def test_slots_reference_existing_variants_or_the_games_own(self):
        by_id = {v["id"]: v for v in CATALOG["variants"]}
        games = {g["appid"] for g in CATALOG["games"]}
        for s in CATALOG["slots"]:
            self.assertIn(s["appid"], games)
            for field in ("ps_variant", "xbox_variant"):
                if s[field] != CATALOG["game_own"]:
                    self.assertIn(s[field], by_id, s["id"])
                    self.assertEqual(by_id[s[field]]["role"], s["role"], s["id"])
            self.assertIn(s["role"], CATALOG["roles"])
            self.assertIn(s["ps_action"], CATALOG["vocabulary"]["ps_action"])
        used = {}
        for v in CATALOG["variants"]:
            for u in v["used_by"]:
                used.setdefault(u["slot"], set()).add(v["id"])
                self.assertEqual(v["confirmed"], True)
        for s in CATALOG["slots"]:
            for field in ("ps_variant", "xbox_variant"):
                if s[field] != CATALOG["game_own"]:
                    self.assertIn(s[field], used[s["id"]])
        self.assertEqual([v["id"] for v in CATALOG["variants"] if v["confirmed"] != bool(v["used_by"])], [])
        for g in CATALOG["games"]:
            self.assertEqual(g["slots"], sum(1 for s in CATALOG["slots"] if s["appid"] == g["appid"]))

    def test_every_tag_is_in_the_vocabulary(self):
        vocab = CATALOG["vocabulary"]
        for v in CATALOG["variants"]:
            for k, val in v["tags"].items():
                self.assertIn(val, vocab[k], v["id"])
