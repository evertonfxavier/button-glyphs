class DedupeTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.masks = self.root / bc.MASKS
        self.masks.mkdir(parents=True)
        self.sources = json.loads((ROOT / bc.SOURCES).read_text())
        self.px = bytes([255, 255, 255, 255, 0, 0, 0, 0] * 8)

    def tearDown(self):
        self.tmp.cleanup()

    def rel(self, name):
        return "%s/%s" % (bc.MASKS, name)

    def test_identical_pixels_are_one_variant_with_every_user(self):
        image.write_png(str(self.masks / "cross.png"), self.px, 4, 4)
        png_with_extra_chunk(str(self.masks / "cross_copy.png"), self.px, 4, 4)      # other bytes, same pixels
        other = bytearray(self.px)
        other[0] = 0
        image.write_png(str(self.masks / "circle.png"), bytes(other), 4, 4)
        self.assertNotEqual((self.masks / "cross.png").read_bytes(), (self.masks / "cross_copy.png").read_bytes())
        paths = bc.scan_art(self.root)
        self.assertEqual(len(paths), 3)
        hints = {self.rel("cross.png"): "a", self.rel("cross_copy.png"): "a", self.rel("circle.png"): "b"}
        variants, path_to_id = bc.build_variants(self.root, paths, self.sources, hints)
        self.assertEqual(len(variants), 2)
        merged = next(v for v in variants if v["role"] == "a")
        self.assertEqual(merged["file"], self.rel("cross.png"))
        self.assertEqual(merged["same_pixels_as"], [self.rel("cross_copy.png")])
        self.assertEqual(path_to_id[self.rel("cross.png")], path_to_id[self.rel("cross_copy.png")])
        self.assertNotEqual(path_to_id[self.rel("cross.png")], path_to_id[self.rel("circle.png")])
        self.assertEqual(len({v["id"] for v in variants}), 2)

    def test_same_pixels_but_other_size_are_not_merged(self):
        image.write_png(str(self.masks / "cross.png"), self.px, 4, 4)
        image.write_png(str(self.masks / "square.png"), self.px, 8, 2)        # same bytes, other geometry
        hints = {self.rel("cross.png"): "a", self.rel("square.png"): "x"}
        variants, _ = bc.build_variants(self.root, bc.scan_art(self.root), self.sources, hints)
        self.assertEqual(len(variants), 2)

    def test_identical_svgs_merge_and_a_conflicting_role_is_refused(self):
        svg = self.root / bc.SVG_DIR / "ps"
        svg.mkdir(parents=True)
        body = '<svg xmlns="http://www.w3.org/2000/svg" width="26" height="26"><circle r="3"/></svg>'
        (svg / "plain-cross.svg").write_text(body)
        (svg / "outline-blue-cross.svg").write_text(body)       # same bytes, same role (a)
        variants, ids = bc.build_variants(self.root, bc.scan_art(self.root), self.sources)
        self.assertEqual(len(variants), 1)
        self.assertEqual(variants[0]["viewbox"], "26x26")
        self.assertEqual(len(variants[0]["same_pixels_as"]), 1)
        (svg / "plain-circle.svg").write_text(body)             # same bytes, role b: ambiguous
        with self.assertRaises(bc.CatalogError):
            bc.build_variants(self.root, bc.scan_art(self.root), self.sources)

    def test_a_svg_no_rule_matches_is_refused(self):
        svg = self.root / bc.SVG_DIR / "ps"
        svg.mkdir(parents=True)
        (svg / "mystery-icon.svg").write_text('<svg width="1" height="1"/>')
        with self.assertRaises(bc.CatalogError) as cm:
            bc.build_variants(self.root, bc.scan_art(self.root), self.sources)
        self.assertIn("mystery-icon", str(cm.exception))

    def test_unknown_art_type_is_refused(self):
        (self.masks / "note.jpg").write_bytes(b"x")
        with self.assertRaises(bc.CatalogError):
            bc.scan_art(self.root)


def variant(vid, role, kind, size, style="ps", used=True, **tags):
    w, h = (None, None) if size == "vector" else map(int, size.split("x"))
    t = {"style": style, "shape": "disc", "shading": "flat", "label": "symbol", "colour": "mono-light",
         "background": "transparent"}
    t.update(tags)
    return {"id": vid, "role": role, "kind": kind, "size": size, "width": w, "height": h, "tags": t,
            "file": "x/%s" % vid, "origin": "o", "used_by": [{"appid": "1", "slot": "1:k:a", "as": "ps"}] if used else [],
            "confirmed": used}


