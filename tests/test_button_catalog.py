class FindTests(unittest.TestCase):
    def ids(self, **kw):
        return [v["id"] for v, _ in bc.rank(SYNTH, **kw)]

    def test_exact_size_beats_nearest(self):
        ranked = self.ids(role="a", size=(28, 23))
        self.assertEqual(ranked[0], "a.px28")
        ranked = self.ids(role="a", size=(13, 13), style="ps")
        self.assertEqual(ranked[:2], ["a.px13", "a.lib13"])      # exact first; confirmed use breaks the tie
        self.assertLess(ranked.index("a.lib13"), ranked.index("a.xbox13"))   # wrong style after the same-size ps ones
        self.assertLess(ranked.index("a.px13"), ranked.index("a.vec"))

    def test_style_is_a_soft_preference_among_equals(self):
        ranked = self.ids(role="a", size=(13, 13), style="xbox")
        self.assertEqual(ranked[0], "a.xbox13")
        self.assertIn("a.px13", ranked)

    def test_role_kind_and_game_filters(self):
        self.assertEqual(self.ids(role="b"), ["b.px13"])
        self.assertEqual(set(self.ids(role="a", kind="vector")), {"a.vec"})
        self.assertNotIn("a.lib13", self.ids(role="a", game="1"))
        self.assertEqual(self.ids(role="a", game="2"), [])

    def test_a_size_with_no_exact_match_gives_the_nearest_and_says_resize(self):
        hits = bc.rank(SYNTH, role="a", size=(14, 14))
        best, info = hits[0]
        self.assertEqual(best["size"], "13x13")
        self.assertFalse(info["exact"])
        self.assertIn("resize", info["hint"])
        self.assertTrue(info["hint"].startswith("resize/restyle needed"))
        # nearest by area and aspect: 28x23 is farther from 14x14 than 13x13
        order = [v["id"] for v, _ in hits]
        self.assertLess(order.index("a.px13"), order.index("a.px28"))
        self.assertLess(order.index("a.px28"), order.index("a.mask"))

    def test_exact_and_matching_style_is_drop_in(self):
        best, info = bc.rank(SYNTH, role="a", size=(28, 23), kind="pixel", game="1")[0]
        self.assertEqual((best["id"], info["hint"]), ("a.px28", "drop-in"))
        self.assertIn("restyle", dict((v["id"], i) for v, i in bc.rank(SYNTH, "a", (13, 13), "ps"))["a.xbox13"]["hint"])

    def test_vector_needs_a_render(self):
        info = dict((v["id"], i) for v, i in bc.rank(SYNTH, "a", (40, 40)))["a.vec"]
        self.assertIn("render the vector at 40x40", info["hint"])

    def test_unknown_role_is_no_variant_and_exit_zero(self):
        self.assertEqual(self.ids(role="zzz"), [])
        text = "\n".join(bc.format_find(SYNTH, "zzz"))
        self.assertTrue(text.startswith("no variant"))
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            self.assertEqual(bc.main(["find", "--role", "zzz"]), 0)
        self.assertIn("no variant", out.getvalue())

    def test_known_role_with_nothing_matching_says_no_variant(self):
        out = "\n".join(bc.format_find(SYNTH, "a", game="2"))
        self.assertTrue(out.startswith("no variant"))

    def test_alias_resolves_to_the_standard_role(self):
        out = "\n".join(bc.format_find(SYNTH, "legs", (13, 13)))
        self.assertIn("alias of a", out)
        self.assertIn("a.px13", out)

    def test_tag_preference(self):
        ranked = self.ids(role="a", size=(13, 13), tags={"style": "xbox"})
        self.assertEqual(ranked[0], "a.xbox13")

    def test_ranking_is_deterministic(self):
        self.assertEqual(self.ids(role="a", size=(13, 13)), self.ids(role="a", size=(13, 13)))

    def test_size_must_look_like_wxh(self):
        with self.assertRaises(ValueError):
            bc.parse_size("13")
        self.assertEqual(bc.parse_size("28x23"), (28, 23))
        err = io.StringIO()
        with contextlib.redirect_stderr(err):
            self.assertEqual(bc.main(["find", "--role", "a", "--size", "wide"]), 2)

    def test_real_catalog_queries(self):
        hits = bc.rank(CATALOG, "a", (13, 13))
        self.assertEqual(hits[0][0]["id"], "a.pixel.sfh-menu-xbox-a-13x13")
        self.assertEqual(hits[0][1]["hint"], "drop-in")
        hits = bc.rank(CATALOG, "dpad_up", (28, 23))
        self.assertEqual(hits[0][0]["id"], "dpad_up.pixel.sfh-tooltip-dpadup-28x23")
        self.assertEqual(bc.rank(CATALOG, "nothing", (1, 1)), [])
        text = "\n".join(bc.format_find(CATALOG, "lb", (17, 15), "ps"))
        self.assertIn("drop-in", text)
