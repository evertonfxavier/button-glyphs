"""Saint Seiya: Soldiers' Soul (Dimps / Bandai Namco, 2015) - Steam appid 348710.

The PC port draws Xbox prompts. Its UI textures live in resource/ui/<language>/*.emb
bundles inside localize.cpk (stored uncompressed), as DXT5 DDS files. Three families carry
Xbox art, in every language:

  pad       BTN_PS3_S / BTN_black (command_STEAM, option_STEAM, btn_STEAM): the controller
            sheet used by menus and tutorials - face buttons, bumpers, triggers, L3/R3,
            START/BACK. (The sheet is named PS3 but holds Xbox art; the console sheets
            with PlayStation art are not used on PC.)
  cockpit   cockpit_arts_btn (battle_STEAM): X / Y / B shown next to the attack commands
  continue  btn (continue_STEAM): the big "A" of the continue screen

The layout (positions of every cell) is identical in all copies. The table of textures
(offset, size, SHA-256) is generated by tools/ssss_build.py; a build whose textures differ
is refused. Sticks, D-pad and the numbered pad buttons are left as they are.
"""
