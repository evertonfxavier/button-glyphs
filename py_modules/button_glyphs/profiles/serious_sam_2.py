"""Serious Sam 2 (Croteam, Serious Engine 2, 2011) - Steam appid 204340.

The PC build draws Xbox prompts everywhere (glossy A/B/X/Y ovals, the black "Use" and white "White" buttons of the
original Xbox pad) from raw-BGRA `.tex` textures inside the root `.gro` archives, which are plain ZIPs. The engine mounts
every root `.gro` in alphabetical order and a LATER archive's entry of the same name wins (the game's own log lists them
in that order). So the PlayStation style is an ADDED archive, `zz_ButtonGlyphs.gro`, that sorts after
`Patch_02_100_800000.gro` and holds six replacement textures; no game file is opened for writing and Original deletes
our file (overlay_patch.py explains states, ledger and write order).

Changed (six 128x128 textures): A_button / B_button / X_button / Y_button become the PlayStation cross / circle /
square / triangle in their symbol colours (outline art), drawn ROUND on the centre of the original tilted oval with the
oval's short side as diameter (the shape is a decision of the owner; ROUND_DIAMETER below is the one number to tune);
Use_button (the dark oval) becomes R1 and White_button (the white oval) becomes L1 as SOLID rectangles (`plain-rectangle-*`, legible on
light and dark): the mapping of those two is a GUESS (they are the Xbox BLACK and WHITE buttons, which the game uses for
"use" and "next weapon") until confirmed in game.

Controller screen: `controller.tex` is replaced by the owner's DualShock 3 picture (`masks/serious/ds3-sam2-1024.png`,
`pad_picture=True` is the default; the owner chose to see it in game). The ARROWS DO NOT MATCH IT: the four arrow
pictures, the stick glow and the leader lines are drawn by Sam2Game.dll at hard-coded layout coordinates of the Xbox "S" pad
(the Xbox has the left stick upper-left and the D-pad lower-left, the DualShock the other way round), so on the DS3 the
left-stick arrows land on the D-pad. Fixing it needs a patch of those coordinates in the DLL (a later step, offsets on the
game page); the arrow gadgets of `CMSControllerOptions.rsc`, `Controller*Arrow`, `AxesButton_glow` stay untouched.

Left alone: the D-pad highlight pictures and the stick cap (they look the same on a PlayStation pad), the keyboard
keycaps, the menu arrows, the four arrow pictures, and the layout `.rsc`.

The table (ids, sizes, SHA-256 of every original entry, the archive that wins it) is generated by tools/serious_build.py
into serious_tables.py; a build whose entries differ is refused.
"""
from . import serious_tables
from .overlay_glyphs import OverlayGlyphProfile, RoundSymbol, WholePicture

APPID = "204340"
TABLE = serious_tables.GAMES[APPID]

# Where each original oval sits in its 128x128 canvas: the opaque box (alpha > 24, x0, y0, x1, y1; 76 x 93, ratio 0.82,
# 26 px margin left and right), measured on the real textures by a dev script, and the colour the game stores under
# alpha 0 (black; the white button keeps white). The symbol is centred on this box.
CELLS = {
    "A_button": {"box": (26, 17, 102, 110), "clear": (0, 0, 0), "art": "glyphs/ps/outline-blue-cross"},
    "B_button": {"box": (26, 17, 102, 110), "clear": (0, 0, 0), "art": "glyphs/ps/outline-red-circle"},
    "X_button": {"box": (26, 17, 102, 110), "clear": (0, 0, 0), "art": "glyphs/ps/outline-purple-square"},
    "Y_button": {"box": (26, 17, 102, 110), "clear": (0, 0, 0), "art": "glyphs/ps/outline-green-triangle"},
    "Use_button": {"box": (26, 17, 102, 110), "clear": (0, 0, 0), "art": "glyphs/ps/plain-rectangle-R1"},       # guess: Xbox BLACK
    "White_button": {"box": (26, 16, 102, 110), "clear": (255, 255, 255), "art": "glyphs/ps/plain-rectangle-L1"},  # guess: Xbox WHITE
}
ROUND_DIAMETER = None          # None = the short side of the box (76); a number overrides it for every symbol
PAD_PICTURE_ART = "masks/serious/ds3-sam2-1024"
PAD_CLEAR = (0, 0, 0)


def key_of(row):
    return row["id"].rsplit("/", 1)[-1]


def entry(row):
    """The fields the overlay strategy needs from one generated table row."""
    return {"key": key_of(row), "path": row["path"], "size": row["size"], "sha256": row["sha256"],
            "crc32": row["crc32"], "gro": row["gro"], "width": row["width"], "height": row["height"]}


def make_profile(pad_picture=True, **overrides):
    rows = {key_of(r): r for r in TABLE["textures"]}
    entries, builders = [], {}
    for key in sorted(CELLS):                       # file order = alphabetical, like the table
        c = CELLS[key]
        if rows[key]["action"] != "replace":
            raise ValueError("%s is not a 'replace' row of the table" % key)
        entries.append(entry(rows[key]))
        builders[key] = RoundSymbol(c["art"], c["box"], c["clear"], ROUND_DIAMETER)
    if pad_picture:
        row = rows["controller"]
        entries.append(entry(row))
        builders["controller"] = WholePicture(PAD_PICTURE_ART, PAD_CLEAR)
    args = dict(
        appid=APPID,
        name="Serious Sam 2",
        entries=entries,
        builders=builders,
        mount=TABLE["mount"],
        load_order=[(n, size) for n, _, size in TABLE["load_order"]],
        archive="zz_ButtonGlyphs.gro",
        vehicle="gro",
        revision=2,
        native_style="xbox",
        roles=[
            ("a", "A / ✕ (bottom)"),
            ("b", "B / ○ (right)"),
            ("x", "X / □ (left)"),
            ("y", "Y / △ (top)"),
            ("rb", "Use (black) / R1 - unconfirmed"),
            ("lb", "White / L1 - unconfirmed"),
        ],
        original_hint="The game's own Xbox prompts (glossy A/B/X/Y ovals, the black and white buttons). "
                      "\"Xbox\" and \"Original\" are the same thing here.",
        notes="Adds one small archive (zz_ButtonGlyphs.gro) next to the game's own; nothing of the game is "
              "modified, Original deletes it.",
        support="partial",
    )
    args.update(overrides)
    return OverlayGlyphProfile(**args)


PROFILE = make_profile()
