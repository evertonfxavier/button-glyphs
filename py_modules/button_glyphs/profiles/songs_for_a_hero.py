"""Songs for a Hero - Definitive Edition (Duma / MonoGame, 2015) - Steam appid 389170.

The PC build shows Xbox prompts everywhere (A/B/X/Y, LB/RB, LT/RT, D-pad, START/BACK), every one
a tiny loose texture under Content/ (XNB v5, 761-2661 bytes, uncompressed RGBA, the pixel block
ends at the end of the file): the in-game tooltips in Content/Tooltip/ and the menu prompts in
Content/Menu/xbox/. There is no PlayStation art and no code switch, so the PlayStation style
replaces 24 of the 36 textures by a bundled drawing of exactly the same size (the profile owner's
own pixel art, masks/sfh/*.png). The original bytes of every file are kept in a backup.

Left alone: the HOLD label, the five left-stick tooltips, the menu D-pad arrows and the L/R stick
caps of the menu - they look the same on a PlayStation pad. The textures are loose files that
have no spare byte for a marker, so the engine reads their state from SHA-256 (files_patch.py).

The table of textures (size, SHA-256 of every original file) is generated by tools/sfh_build.py and
the list of drawn textures by tools/sfh_art.py; a build whose files differ is refused.
"""
from .songs_for_a_hero_art import ART
from .songs_for_a_hero_cells import TEXTURES
from .xnb_pictures import XnbPictureProfile

CONTENT = "Content"


def entry(texture):
    """The fields the files strategy needs (the cell table stays a measured spec, not profile data)."""
    return {
        "key": texture["key"],
        "file": "%s/%s.xnb" % (CONTENT, texture["key"]),
        "width": texture["width"],
        "height": texture["height"],
        "header": texture["pixel_offset"],
        "size": texture["size"],
        "sha256": texture["sha256"],
        "image": ART[texture["key"]],
    }


FILES = [entry(t) for t in TEXTURES if t["key"] in ART]

PROFILE = XnbPictureProfile(
    appid="389170",
    support="full",
    name="Songs for a Hero - Definitive Edition",
    content_dir=CONTENT,
    files=FILES,
    revision=1,
    native_style="xbox",
    roles=[
        ("y", "Y / △ (top)"),
        ("x", "X / □ (left)"),
        ("b", "B / ○ (right)"),
        ("a", "A / ✕ (bottom)"),
    ],
    original_hint="The game's own Xbox prompts. \"Xbox\" and \"Original\" are the same thing here.",
    notes="Replaces 24 tiny texture files under Content/ (about 46 KB) with PlayStation pixel art; "
          "the original files are kept in the plugin's backups.",
)
