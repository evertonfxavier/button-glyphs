#!/usr/bin/env python3
"""Button catalog: every distinct button we drew or mapped for a CONFIRMED game, searchable.

    python3 tools/build_button_catalog.py build            write catalog/catalog.json and docs/button-catalog.md
    python3 tools/build_button_catalog.py build --check    exit 1 with a diff if they are stale (tests and CI use this)
    python3 tools/build_button_catalog.py find --role a --size 13x13 [--style ps|xbox] [--game 389170]
                                                [--kind vector|mask|pixel|picture] [--tag shading=outline] [--limit 8]
    python3 tools/build_button_catalog.py sheet out.png    contact sheet of the variants per role (needs Pillow; not committed)

Why: supporting the next game should start from the closest button that already exists (its role, size and
look), not from zero. `find` ranks the existing variants for a role and a texture size: exact size first, then
the nearest by area and aspect, then the same style/kind, and says `drop-in` or `resize/restyle needed`.

Model (stdlib only; `find`, `build` and `--check` run in CI):
  VARIANT  one distinct art asset of OUR art: an SVG of assets/svg (63 PlayStation + 39 Xbox), a white mask or a
           whole picture in py_modules/button_glyphs/masks, or a native-size pixel picture in masks/sfh. Dedupe: the
           decoded RGBA pixels (PNG) or the file bytes (SVG) are hashed; identical art is ONE variant that lists
           every game slot that uses it (`used_by`).
  SLOT     one button position of a confirmed game (appid, texture key, role, native size, native look, what a
           PlayStation pad needs, which variant we drew there or "game's own: unchanged").
  ROLE     the standard name (a b x y lb rb lt rt l3 r3 lstick* rstick* dpad* start select home touchpad hold
           controller); a game's own names (AC1: head weapon empty legs) are aliases.

Sources of truth - never edit the generated parts by hand:
  catalog/sources.json            HAND-maintained: roles, tag vocabulary, art origins/licences, tag rules, the look of
                                  each game's own buttons. Read its `_readme` first.
  docs/games/<appid>-*.md         "Support level": only `confirmed` / `partly confirmed` games enter the catalog
  button_glyphs.profiles          slots (sizes, roles, keys, ps_action, art used) derived from the generated tables
  assets/svg, masks/              the art itself (every file must be catalogued: a new PNG fails the test until
                                  `build` is run)
The catalog stores OUR art plus metadata about each game's own buttons: never game pixels (rule 13).
"""
