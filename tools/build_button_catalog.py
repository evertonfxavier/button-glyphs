class CatalogError(Exception):
    pass


# --------------------------------------------------------------------------- inputs


def load_sources(root):
    path = Path(root) / SOURCES
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError) as exc:
        raise CatalogError("cannot read %s: %s" % (SOURCES, exc))


def confirmed_pages(root):
    """{appid: page info} of every game page whose Support level is confirmed / partly confirmed."""
    import gen_supported_games as gen
    out = {}
    for page in sorted((Path(root) / "docs" / "games").glob("[0-9]*-*.md")):
        appid = page.name.split("-", 1)[0]
        try:
            info = gen.read_page(Path(root), appid)
        except gen.PageError as exc:
            raise CatalogError(str(exc))
        if info["level"] in CONFIRMED_LEVELS:
            out[appid] = {"page": "docs/games/" + info["page"], "level": info["level"]}
    return out


def scan_art(root):
    """Repo-relative paths of every art file: PNGs under masks/ (incl. masks/sfh) and SVGs under assets/svg."""
    root = Path(root)
    out = []
    for base, suffix in ((root / MASKS, ".png"), (root / SVG_DIR, ".svg")):
        if not base.is_dir():
            continue
        for p in sorted(base.rglob("*")):
            if not p.is_file() or p.name.startswith(".") or p.suffix in SKIP_SUFFIXES:
                continue
            if p.suffix != suffix:
                raise CatalogError("%s: unsupported art file type (only %s is catalogued)" % (
                    p.relative_to(root).as_posix(), suffix))
            out.append(p.relative_to(root).as_posix())
    return sorted(out)


def mask_path(name):
    return "%s/%s.png" % (MASKS, name)


def svg_path(icon):
    return "%s/%s.svg" % (SVG_DIR, icon)


# --------------------------------------------------------------------------- roles and tags


def norm_role(role, sources):
    alias = sources["role_aliases"].get(role)
    return alias[0] if alias else role


def make_svg_classifier(sources):
    rules = [(re.compile(r["match"]), r) for r in sources["svg_rules"]]

    def classify(icon):
        """icon = 'ps/plain-cross' -> (role, detail). CatalogError when no rule matches."""
        for rx, rule in rules:
            m = rx.match(icon)
            if m:
                return m.expand(rule["role"]), rule.get("detail", "")
        raise CatalogError("cannot tell the role of %s.svg: add a rule to svg_rules in catalog/sources.json" % icon)
    return classify


def svg_tags(icon, role, sources):
    style, name = icon.split("/", 1)
    spec = sources["roles"][role]
    label = spec["label"]
    label = label[style] if isinstance(label, dict) else label
    coloured = re.search(r"-(blue|green|red|purple|yellow)(?:-|$)", name)
    return {
        "style": style,
        "shape": spec["shape"],
        "shading": "outline" if "outline" in name else "flat",
        "label": label,
        "colour": ("ps-symbol-colours" if style == "ps" else "xbox-colours") if coloured else "mono-light",
        "background": "transparent",
    }


def png_tags(rule, role, sources):
    tags = dict(rule["tags"])
    spec = sources["roles"][role]
    if "shape" not in tags:
        tags["shape"] = spec["shape"]
    if "label" not in tags:
        label = spec["label"]
        tags["label"] = label[tags["style"]] if isinstance(label, dict) else label
    for roles, extra in rule.get("role_tags", {}).items():
        if role in roles.split(","):
            tags.update(extra)
    return tags


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


# --------------------------------------------------------------------------- variants


def _svg_viewbox(data):
    head = data[:600].decode("utf-8", "replace")
    w = re.search(r'\bwidth="([0-9.]+)"', head)
    h = re.search(r'\bheight="([0-9.]+)"', head)
    return (w.group(1), h.group(1)) if w and h else None


def build_variants(root, paths, sources, role_hint=None):
    """-> (variants, path_to_id). Pure function of the art files and sources.json (tests call it on a temp folder).

    role_hint: {repo path: role} derived from the profiles; PNGs without a hint need `art_roles` in sources.json.
    """
    from button_glyphs import image
    root = Path(root)
    role_hint = role_hint or {}
    classify = make_svg_classifier(sources)
    art_rules = sources["art_rules"]
    groups, order = {}, []
    for rel in paths:
        data = (root / rel).read_bytes()
        if rel.endswith(".svg"):
            key = ("svg", hashlib.sha256(data).hexdigest())
            info = {"sha256": key[1], "viewbox": _svg_viewbox(data)}
        else:
            rgba, w, h = image.read_png(str(root / rel))
            px = hashlib.sha256(("%dx%d:" % (w, h)).encode() + bytes(rgba)).hexdigest()
            key = ("png", px)
            info = {"sha256": hashlib.sha256(data).hexdigest(), "pixels_sha256": px, "w": w, "h": h}
        if key not in groups:
            groups[key] = {"paths": [], "info": info}
            order.append(key)
        groups[key]["paths"].append(rel)

    variants, path_to_id, ids = [], {}, set()
    for key in order:
        g = groups[key]
        primary, info = g["paths"][0], g["info"]
        if key[0] == "svg":
            icons = [p[len(SVG_DIR) + 1:-len(".svg")] for p in g["paths"]]
            classified = {classify(i) for i in icons}
            roles = {r for r, _ in classified}
            if len(roles) != 1:
                raise CatalogError("identical SVGs %s have different roles %s" % (g["paths"], sorted(roles)))
            role, detail = sorted(classified)[0]
            style = icons[0].split("/", 1)[0]
            origin = {"ps": "figma-ps", "xbox": "figma-xbox"}.get(style)
            if origin is None:
                raise CatalogError("%s: unknown icon set %r (add it to build_button_catalog.py)" % (primary, style))
            kind, tags = "vector", svg_tags(icons[0], role, sources)
            size = "vector"
            width = height = None
            stem = icons[0].replace("/", "-")
        else:
            hints = {role_hint[p] for p in g["paths"] if p in role_hint}
            if len(hints) > 1:
                raise CatalogError("%s is used with different roles: %s" % (primary, sorted(hints)))
            role = next(iter(hints), None) or next((sources["art_roles"][p] for p in g["paths"]
                                                   if p in sources["art_roles"]), None)
            if role is None:
                raise CatalogError("cannot tell the role of %s: no registered profile uses it; add it to art_roles "
                                   "in catalog/sources.json" % primary)
            rule = next((r for r in art_rules if fnmatch.fnmatchcase(primary, r["match"])), None)
            if rule is None:
                raise CatalogError("%s: no art_rules entry matches; add one to catalog/sources.json" % primary)
            if role not in sources["roles"]:
                raise CatalogError("%s: role %r is not in the roles table of catalog/sources.json" % (primary, role))
            kind, origin, detail = rule["kind"], rule["origin"], ""
            tags = png_tags(rule, role, sources)
            width, height = info["w"], info["h"]
            size = "%dx%d" % (width, height)
            stem = slug(primary[len(MASKS) + 1:-len(".png")]) + "-" + size
        if role not in sources["roles"]:
            raise CatalogError("%s: role %r is not in the roles table of catalog/sources.json" % (primary, role))
        vid = "%s.%s.%s" % (role, "svg" if kind == "vector" else kind, slug(stem))
        if vid in ids:
            raise CatalogError("variant id %s is not unique (%s)" % (vid, primary))
        ids.add(vid)
        variant = {
            "id": vid, "role": role, "kind": kind, "size": size, "width": width, "height": height,
            "tags": {k: tags[k] for k in TAG_KEYS},
            "file": primary,
        }
        if len(g["paths"]) > 1:
            variant["same_pixels_as"] = g["paths"][1:]
        variant["sha256"] = info["sha256"]
        if "pixels_sha256" in info:
            variant["pixels_sha256"] = info["pixels_sha256"]
        if info.get("viewbox"):
            variant["viewbox"] = "%sx%s" % info["viewbox"]
        if detail:
            variant["detail"] = detail
        variant["origin"] = origin
        variant["used_by"] = []
        variant["confirmed"] = False
        variants.append(variant)
        for p in g["paths"]:
            path_to_id[p] = vid
    return variants, path_to_id


# --------------------------------------------------------------------------- slots (derived from the profile tables)


class Ctx:
    def __init__(self, root, sources):
        self.root = Path(root)
        self.sources = sources
        self.svg_role = make_svg_classifier(sources)

    def role(self, role):
        r = norm_role(role, self.sources)
        if r not in self.sources["roles"]:
            raise CatalogError("role %r is not in the roles table of catalog/sources.json" % role)
        return r

    def action(self, role, has_art):
        action = self.sources["roles"][role]["ps_action"]
        return "redraw" if has_art and action == "same" else action

    def png_size(self, rel):
        from button_glyphs import image
        _, w, h = image.read_png(str(self.root / rel))
        return "%dx%d" % (w, h)


def _size(rect):
    x0, y0, x1, y1 = rect
    return "%dx%d" % (x1 - x0 + 1, y1 - y0 + 1)


def _area(size):
    w, h = size.split("x")
    return int(w) * int(h)


def _merge(slots, key, base):
    """Slots that differ only by hud scale / archive / copy are ONE slot: merge sizes and counts."""
    if key in slots:
        s = slots[key]
        s["count"] += base.get("count", 1)
        for size in base["sizes"]:
            if size not in s["sizes"]:
                s["sizes"].append(size)
        for tex in base.get("textures", ()):
            s["_textures"].add(tex)
    else:
        base = dict(base)
        base["count"] = base.get("count", 1)
        base["_textures"] = set(base.pop("textures", ()))
        slots[key] = base


def slots_regions(profile, ctx):
    from button_glyphs.profiles.region_glyphs import LABEL, SYMBOL
    slots = {}
    for region in profile.regions:
        group = region["key"].split("/")[0]
        for cell in region["cells"]:
            role = ctx.role(cell["role"])
            name = SYMBOL[cell["role"]] if cell["kind"] in ("disc", "letter") else LABEL[cell["role"]]
            k = (group, cell["kind"], role)
            _merge(slots, k, {
                "role": role, "cell": cell["kind"], "family": "%s:%s" % (group, cell["kind"]),
                "sizes": [_size(cell["draw"])], "textures": [region["key"]], "ps_art": mask_path(name),
                "ps_action": ctx.action(role, True)})
            slots[k].setdefault("_modes", set()).add(cell["style"])
        spec = region.get("replace")
        if spec:
            _merge(slots, (group, "picture", "controller"), {
                "role": "controller", "cell": "picture", "family": "%s:picture" % group,
                "sizes": [ctx.png_size(mask_path(spec["image"]))], "textures": [region["key"]],
                "ps_art": mask_path(spec["image"]), "ps_action": ctx.action("controller", True)})
    out = []
    for (group, cell, role), s in slots.items():
        textures = sorted(s.pop("_textures"))
        s["key"] = "%s/*" % group if len(textures) > 1 else textures[0]
        s["textures"] = len(textures)
        s["sizes"].sort(key=lambda z: (_area(z), z))
        modes = sorted(s.pop("_modes", ()))
        if modes:
            s["note"] = "glyph drawn as: " + ", ".join(
                {"hole": "hole in the shape", "solid": "one colour", "ps": "role colour"}[m] for m in modes)
        out.append(s)
    return out


def slots_dxt(profile, ctx):
    textures = {}
    for region in profile.regions:
        textures.setdefault(region["layout"], []).append(region)
    out = []
    for layout, cells in profile.layouts.items():
        regions = textures.get(layout, [])
        if not regions:
            continue
        tex = "%dx%d" % (regions[0]["width"], regions[0]["height"])
        for cell in cells:
            for rect, icon in cell["draws"]:
                role, _ = ctx.svg_role(icon)
                role = ctx.role(role)
                out.append({"key": "%s layout (%d,%d)" % (layout, rect[0], rect[1]), "role": role, "family": layout,
                            "sizes": [_size(rect)], "textures": len(regions), "texture_size": tex,
                            "ps_art": svg_path(icon), "ps_action": ctx.action(role, True)})
    return out


def slots_files(profile, ctx):
    import importlib
    mod = importlib.import_module("button_glyphs.profiles." + CELLS_MODULES[profile.appid])
    art = {e["key"]: e["image"] for e in profile.files}
    out = []
    for tex in list(mod.TEXTURES) + list(getattr(mod, "EXTRA_TEXTURES", [])):
        role = ctx.role(tex["role"])
        has_art = tex["key"] in art
        action = tex["ps_action"]
        action = ("redraw" if has_art else "same") if action == "optional" else action
        slot = {"key": tex["key"], "role": role, "family": tex["family"],
                "sizes": ["%dx%d" % (tex["width"], tex["height"])], "ps_action": action,
                "ps_art": mask_path(art[tex["key"]]) if has_art else None}
        if "cells" in tex:
            kinds = sorted({c["kind"] for c in tex["cells"]})
            slot["cell"] = "+".join(kinds)
        out.append(slot)
    return out


def slots_forge(profile, ctx):
    slots = {}
    for index, target in enumerate(profile.targets()):
        styles = target.get("styles", profile.styles)
        primary = index == 0
        for spec in target["textures"]:
            name = spec.get("name") or spec["label"]
            for game_role, box in spec["boxes"].items():
                role = ctx.role(game_role)
                if primary:
                    family = "hud-a" if spec.get("clear_all") else ("font-white" if spec.get("tint") else "font-colour")
                elif name.endswith("_Color_Map"):
                    family = "area-colour"
                elif role in ("lstick", "rstick", "lt", "rt"):
                    family = "area-pad"
                else:
                    family = "area-white"
                ps = profile.icons_for(spec, "ps")[game_role] if "ps" in styles else None
                xbox = profile.icons_for(spec, "xbox")[game_role] if "xbox" in styles else None
                base = {"key": spec["label"] if primary else name, "role": role,
                        "family": family, "sizes": [_size(box)], "texture_size": "%dx%d" % (spec["width"], spec["height"]),
                        "ps_art": svg_path(ps) if ps else None, "xbox_art": svg_path(xbox) if xbox else None,
                        "ps_action": ctx.action(role, bool(ps)), "count": 1}
                if game_role != role:
                    base["game_role"] = game_role
                _merge(slots, (base["key"], role), base)
    out = []
    for s in slots.values():
        s.pop("_textures")
        if s["count"] > 1:
            s["note"] = "same texture in %d area archives" % s["count"]
        out.append(s)
    return out


ADAPTERS = {"regions": slots_regions, "dxt-regions": slots_dxt, "loose-files": slots_files,
            "forge-glyphs": slots_forge}


def derive_slots(profile, ctx):
    adapter = ADAPTERS.get(profile.kind)
    return adapter(profile, ctx) if adapter else []


def manual_slots(entry, ctx):
    out = []
    for m in entry.get("manual_slots", []):
        role = ctx.role(m["role"])
        s = {"key": m["key"], "role": role, "family": m["family"],
             "sizes": [m["size"]] if m.get("size") else [], "ps_art": None, "ps_action": m["ps_action"]}
        if m.get("note"):
            s["note"] = m["note"]
        out.append(s)
    return out


# --------------------------------------------------------------------------- catalog


def lookup_family(families, family, role):
    for k, v in families.items():
        if "/" in k:
            fam, roles = k.split("/", 1)
            if fam == family and role in roles.split(","):
                return v
    return families.get(family)


def validate_tags(where, tags, vocab):
    for k, v in tags.items():
        if k not in vocab or v not in vocab[k]:
            raise CatalogError("%s: tag %s=%r is not in the vocabulary of catalog/sources.json" % (where, k, v))


def build_catalog(root=ROOT):
    root = Path(root)
    sources = load_sources(root)
    from button_glyphs.profiles import PROFILES
    from button_glyphs.profiles.region_glyphs import PS_COLORS, SYMBOL
    # the PlayStation symbol colours are read from the profile code, never retyped
    ps_colors = {r: {"symbol": SYMBOL[r], "hex": "#%02x%02x%02x" % (c[2], c[1], c[0])} for r, c in PS_COLORS.items()}
    vocab = sources["vocabulary"]
    vocab["colour"]["ps-symbol-colours"] = "PlayStation symbol colours (region_glyphs.PS_COLORS): " + ", ".join(
        "%s %s" % (v["symbol"], v["hex"]) for v in ps_colors.values())
    pages = confirmed_pages(root)
    games_src = sources["games"]
    for appid in sorted(set(pages) - set(games_src)):
        raise CatalogError("game %s is confirmed on its page but is not in catalog/sources.json: add it (families, "
                           "short name) and run build" % appid)
    for appid in sorted(set(games_src) - set(pages)):
        raise CatalogError("catalog/sources.json lists game %s but its page does not say confirmed / partly "
                           "confirmed: remove it" % appid)
    ctx = Ctx(root, sources)

    # derive the slots of every registered profile (the art roles come from all of them, the catalog keeps confirmed)
    derived = {appid: derive_slots(p, ctx) for appid, p in PROFILES.items()}
    role_hint = {}
    for appid, slots in derived.items():
        for s in slots:
            for art in (s.get("ps_art"), s.get("xbox_art")):
                if art and art.endswith(".png"):
                    role_hint[art] = s["role"]
    paths = scan_art(root)
    variants, path_to_id = build_variants(root, paths, sources, role_hint)
    by_id = {v["id"]: v for v in variants}

    games, slots_out = [], []
    for appid in sorted(pages, key=lambda a: PROFILES[a].name.lower() if a in PROFILES else a):
        if appid not in PROFILES:
            raise CatalogError("game %s is confirmed but has no registered profile" % appid)
        profile, entry = PROFILES[appid], games_src[appid]
        families = entry["families"]
        raw = derived[appid] + manual_slots(entry, ctx)
        if not raw:
            raise CatalogError("game %s has no slots" % appid)
        used_families = set()
        seen_ids = {}
        for s in raw:
            fam = lookup_family(families, s["family"], s["role"])
            if fam is None:
                raise CatalogError("game %s: slot %s (family %r, role %s) has no entry in games.%s.families of "
                                   "catalog/sources.json" % (appid, s["key"], s["family"], s["role"], appid))
            used_families.add(s["family"])
            native = dict(fam["native_look"])
            ps_id = xbox_id = GAME_OWN
            for field, art in (("ps", s.get("ps_art")), ("xbox", s.get("xbox_art"))):
                if art:
                    if art not in path_to_id:
                        raise CatalogError("game %s: slot %s uses %s, which is not catalogued art" % (appid, s["key"], art))
                    vid = path_to_id[art]
                    if by_id[vid]["role"] != s["role"]:
                        raise CatalogError("game %s: slot %s (role %s) uses %s whose role is %s" % (
                            appid, s["key"], s["role"], vid, by_id[vid]["role"]))
                    if field == "ps":
                        ps_id = vid
                    else:
                        xbox_id = vid
            if ps_id != GAME_OWN:
                ps_look = {k: by_id[ps_id]["tags"][k] for k in LOOK_KEYS}
            else:
                ps_look = dict(native)
            ps_look.update(fam.get("ps_look", {}))
            validate_tags("game %s %s native_look" % (appid, s["key"]), native, vocab)
            validate_tags("game %s %s ps_look" % (appid, s["key"]), ps_look, vocab)
            sid = "%s:%s:%s" % (appid, s["key"], s["role"])
            if s.get("cell"):
                sid += ":" + s["cell"]
            if sid in seen_ids:
                seen_ids[sid] += 1
                sid += "#%d" % seen_ids[sid]
            else:
                seen_ids[sid] = 0
            note = "; ".join(x for x in (s.get("note"), fam.get("note")) if x)
            if s.get("game_role"):
                note = "game role '%s' = %s; %s" % (s["game_role"], s["role"], note) if note else \
                    "game role '%s' = %s" % (s["game_role"], s["role"])
            slot = {"id": sid, "appid": appid, "key": s["key"], "role": s["role"]}
            if s.get("game_role"):
                slot["game_role"] = s["game_role"]
            slot.update({"family": s["family"], "sizes": s["sizes"], "count": s.get("count", 1)})
            if s.get("textures"):
                slot["textures"] = s["textures"]
            if s.get("texture_size"):
                slot["texture_size"] = s["texture_size"]
            if s.get("cell"):
                slot["cell"] = s["cell"]
            slot.update({"native_look": native, "ps_action": s["ps_action"], "ps_look": ps_look,
                         "ps_variant": ps_id, "xbox_variant": xbox_id})
            validate_tags("slot " + sid, {"ps_action": s["ps_action"]}, vocab)
            if note:
                slot["note"] = note
            slots_out.append(slot)
            for field, vid in (("ps", ps_id), ("xbox", xbox_id)):
                if vid != GAME_OWN:
                    by_id[vid]["used_by"].append({"appid": appid, "slot": sid, "as": field})
        games.append({"appid": appid, "name": profile.name, "short": entry["short"], "level": pages[appid]["level"],
                      "page": pages[appid]["page"], "strategy": profile.kind,
                      "slots": sum(1 for x in slots_out if x["appid"] == appid)})

    for v in variants:
        v["used_by"].sort(key=lambda u: (u["appid"], u["slot"], u["as"]))
        v["confirmed"] = bool(v["used_by"])
    role_order = list(sources["roles"])
    variants.sort(key=lambda v: (role_order.index(v["role"]), KIND_ORDER[v["kind"]], v["id"]))
    slots_out.sort(key=lambda s: (s["appid"], s["id"]))
    roles = {}
    for r, spec in sources["roles"].items():
        roles[r] = dict(spec, variants=sum(1 for v in variants if v["role"] == r),
                        slots=sum(1 for s in slots_out if s["role"] == r))
    return {
        "_generated": GENERATED,
        "schema": SCHEMA,
        "game_own": GAME_OWN,
        "counts": {"games": len(games), "roles": len(roles), "variants": len(variants), "slots": len(slots_out),
                   "variants_used_by_confirmed_games": sum(1 for v in variants if v["confirmed"])},
        "ps_colors": ps_colors,
        "vocabulary": vocab,
        "origins": sources["origins"],
        "roles": roles,
        "role_aliases": {k: {"role": v[0], "note": v[1]} for k, v in sorted(sources["role_aliases"].items())},
        "games": games,
        "variants": variants,
        "slots": slots_out,
    }


