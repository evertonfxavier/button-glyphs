def make_sheet(cat, root, out_path):
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        raise CatalogError("the sheet command needs Pillow (pip install pillow); build/find/check do not")
    root = Path(root)
    cell, label_h, pad = 96, 26, 6
    rows = []
    for role in cat["roles"]:
        vs = [v for v in cat["variants"] if v["role"] == role]
        if vs:
            rows.append((role, vs))
    width = max(len(vs) for _, vs in rows) * (cell + pad) + 150
    im = Image.new("RGBA", (width, len(rows) * (cell + label_h + pad)), (58, 58, 68, 255))
    d = ImageDraw.Draw(im)
    for r, (role, vs) in enumerate(rows):
        y = r * (cell + label_h + pad)
        d.text((4, y + cell // 2), role, fill=(255, 255, 0, 255))
        for i, v in enumerate(vs):
            x = 150 + i * (cell + pad)
            if v["kind"] == "vector":
                icon = root / "py_modules" / "button_glyphs" / "glyphs" / (v["file"].split("assets/svg/")[1][:-4] + ".png")
            else:
                icon = root / v["file"]
            if icon.exists():
                g = Image.open(icon).convert("RGBA")
                scale = max(1, min(cell // max(g.size), 8)) if max(g.size) < cell else 1
                if scale > 1:
                    g = g.resize((g.width * scale, g.height * scale), Image.NEAREST)
                g.thumbnail((cell, cell))
                im.paste(g, (x + (cell - g.width) // 2, y + label_h + (cell - g.height) // 2), g)
            d.text((x, y + 2), v["id"].split(".", 2)[2][:20], fill=(200, 230, 255, 255))
            d.text((x, y + 13), "%s %s" % (v["kind"], v["size"]), fill=(160, 160, 170, 255))
    im.save(out_path)
    return len(rows)


