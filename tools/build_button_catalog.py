def _scalar(o):
    return not isinstance(o, (dict, list))


def _dump(o, ind=0):
    """json with small flat dicts/lists on one line: readable and deterministic."""
    pad = " " * ind
    if isinstance(o, dict):
        if all(_scalar(v) for v in o.values()) and len(json.dumps(o, ensure_ascii=False)) < 160:
            return json.dumps(o, ensure_ascii=False)
        items = ["%s %s: %s" % (pad, json.dumps(k, ensure_ascii=False), _dump(v, ind + 1)) for k, v in o.items()]
        return "{\n" + ",\n".join(items) + "\n" + pad + "}"
    if isinstance(o, list):
        if all(_scalar(v) for v in o) and len(json.dumps(o, ensure_ascii=False)) < 160:
            return json.dumps(o, ensure_ascii=False)
        items = [pad + " " + _dump(v, ind + 1) for v in o]
        return "[\n" + ",\n".join(items) + "\n" + pad + "]"
    return json.dumps(o, ensure_ascii=False)


def render_json(cat):
    return _dump(cat) + "\n"


def _look(tags):
    vals = [tags[k] for k in LOOK_KEYS]
    return "unknown" if all(v == "unknown" for v in vals) else " / ".join(v for v in vals)


def _sizes(slot):
    return ", ".join(slot["sizes"]) or "not recorded"


