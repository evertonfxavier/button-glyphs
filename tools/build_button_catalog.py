def parse_size(text):
    m = re.fullmatch(r"(\d+)x(\d+)", text or "")
    if not m or int(m.group(1)) < 1 or int(m.group(2)) < 1:
        raise ValueError("size must look like 13x13, got %r" % text)
    return int(m.group(1)), int(m.group(2))


def rank(cat, role, size=None, style=None, kind=None, game=None, tags=None):
    """Variants of `role` ranked for a texture of `size`: [(variant, info)] best first."""
    out = []
    for v in cat["variants"]:
        if v["role"] != role or (kind and v["kind"] != kind):
            continue
        if game and not any(u["appid"] == game for u in v["used_by"]):
            continue
        if size is None:
            exact, dist = False, 0.0
        elif v["kind"] == "vector":
            exact, dist = False, VECTOR_DIST
        else:
            w, h = size
            exact = (v["width"], v["height"]) == (w, h)
            dist = abs(math.log(v["width"] * v["height"] / (w * h))) + abs(math.log((v["width"] / v["height"]) / (w / h)))
        style_miss = bool(style and v["tags"]["style"] not in (style, "neutral"))
        tag_miss = sum(1 for k, val in (tags or {}).items() if v["tags"].get(k) != val)
        key = (0 if exact else 1, round(dist, 6), int(style_miss), tag_miss, KIND_ORDER[v["kind"]],
               0 if v["confirmed"] else 1, v["id"])
        if size is None:
            hint = "no --size given"
        else:
            need = []
            if not exact:
                need.append("render the vector at %dx%d" % size if v["kind"] == "vector" else "resize")
            if style_miss:
                need.append("restyle")
            hint = "drop-in" if not need else "resize/restyle needed (%s)" % ", ".join(need)
        out.append((key, v, {"exact": exact, "hint": hint, "style_miss": style_miss, "tag_miss": tag_miss}))
    out.sort(key=lambda t: t[0])
    return [(v, info) for _, v, info in out]


def format_find(cat, role, size=None, style=None, kind=None, game=None, tags=None, limit=8):
    names = {g["appid"]: g for g in cat["games"]}
    slot_by_id = {s["id"]: s for s in cat["slots"]}
    raw_role = role
    note = ""
    if role in cat["role_aliases"]:
        note = "(%s is an alias of %s: %s)" % (role, cat["role_aliases"][role]["role"], cat["role_aliases"][role]["note"])
        role = cat["role_aliases"][role]["role"]
    want = "role %s" % role + (", size %dx%d" % size if size else "") + (", style %s" % style if style else "") \
        + (", kind %s" % kind if kind else "") + (", game %s" % game if game else "") \
        + "".join(", %s=%s" % kv for kv in sorted((tags or {}).items()))
    if role not in cat["roles"]:
        return ["no variant: unknown role %r. Known roles: %s" % (raw_role, ", ".join(cat["roles"]))]
    hits = rank(cat, role, size, style, kind, game, tags)
    if not hits:
        return ["no variant for %s (the role exists but nothing matches the filters)" % want]
    lines = ["%d variant%s for %s" % (len(hits), "" if len(hits) == 1 else "s", want)]
    if note:
        lines.append(note)
    for i, (v, info) in enumerate(hits[:limit], 1):
        users = ["%s (%s, %s) in %s" % (names[u["appid"]]["name"], u["appid"], names[u["appid"]]["level"],
                                        slot_by_id.get(u["slot"], {}).get("key", u["slot"]))
                 for u in v["used_by"] if u["as"] == "ps"] or ["library only (no confirmed game uses it yet)"]
        shown = v["kind"] if v["kind"] == "vector" else "%s %s" % (v["kind"], v["size"])
        lines += ["", "%d. %s   [%s]   %s" % (i, v["id"], shown, info["hint"]),
                  "   tags   : " + " ".join("%s=%s" % (k, v["tags"][k]) for k in TAG_KEYS),
                  "   file   : " + v["file"],
                  "   origin : %s - %s" % (v["origin"], cat["origins"][v["origin"]]),
                  "   used by: " + users[0]] + ["            " + u for u in users[1:4]]
        if len(users) > 4:
            lines.append("            ... %d more" % (len(users) - 4))
        if v.get("detail"):
            lines.append("   detail : " + v["detail"])
    if len(hits) > limit:
        lines += ["", "... %d more (use --limit)" % (len(hits) - limit)]
    slots = [s for s in cat["slots"] if s["role"] == role and (not game or s["appid"] == game)]
    if slots:
        def sdist(s):
            if size is None or not s["sizes"]:
                return 99.0
            return min(abs(math.log(_area(z) / (size[0] * size[1]))) for z in s["sizes"])
        slots.sort(key=lambda s: (sdist(s), s["id"]))
        lines += ["", "Confirmed games' slots of this role (their own look, nearest size first):"]
        for s in slots[:5]:
            lines.append("  %s  %s  size %s  native %s  -> %s" % (
                names[s["appid"]]["short"], s["key"], _sizes(s), _look(s["native_look"]),
                s["ps_variant"] if s["ps_variant"] != cat["game_own"] else "game's own (" + s["ps_action"] + ")"))
    return lines


