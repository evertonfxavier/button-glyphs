def check(root):
    """Print a diff-style message per stale file; return the number of stale files."""
    root = Path(root)
    stale = 0
    for path, content in targets(root):
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        stale += 1
        rel = path.relative_to(root).as_posix()
        if current is None:
            print("missing: %s" % rel, file=sys.stderr)
            continue
        diff = list(difflib.unified_diff(current.splitlines(), content.splitlines(), "%s (committed)" % rel,
                                         "%s (regenerated)" % rel, lineterm="", n=0))
        print("out of date: %s (%d changed lines)" % (rel, sum(1 for l in diff if l[:1] in "+-" and l[:3] not in ("+++", "---"))),
              file=sys.stderr)
        for line in diff[:24]:
            print("  " + line, file=sys.stderr)
        if len(diff) > 24:
            print("  ... %d more diff lines" % (len(diff) - 24), file=sys.stderr)
    if stale:
        print("run: python3 tools/build_button_catalog.py build", file=sys.stderr)
    return stale


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--check", action="store_true", help="same as `build --check`")
    sub = ap.add_subparsers(dest="cmd")
    b = sub.add_parser("build", help="regenerate catalog/catalog.json and docs/button-catalog.md")
    b.add_argument("--check", action="store_true", dest="check_b", help="do not write; exit 1 if stale")
    f = sub.add_parser("find", help="rank the existing variants for a role (and size / style)")
    f.add_argument("--role", required=True)
    f.add_argument("--size", help="WxH of the texture to fill, e.g. 13x13")
    f.add_argument("--style", choices=("ps", "xbox"), help="console look wanted (a soft preference)")
    f.add_argument("--game", help="only variants used by this appid")
    f.add_argument("--kind", choices=tuple(KIND_ORDER))
    f.add_argument("--tag", action="append", default=[], metavar="KEY=VALUE", help="soft preference on a tag, repeatable")
    f.add_argument("--limit", type=int, default=8)
    s = sub.add_parser("sheet", help="labelled contact sheet of the variants per role (Pillow; not committed)")
    s.add_argument("out")
    args = ap.parse_args(argv)
    root = Path(args.root)
    try:
        if args.cmd == "find":
            cat = json.loads((root / JSON_OUT).read_text())
            size = parse_size(args.size) if args.size else None
            tags = {}
            for t in args.tag:
                k, _, v = t.partition("=")
                if k not in TAG_KEYS or not v:
                    raise ValueError("--tag needs KEY=VALUE with KEY one of %s" % ", ".join(TAG_KEYS))
                tags[k] = v
            print("\n".join(format_find(cat, args.role, size, args.style, args.kind, args.game, tags, args.limit)))
            return 0
        if args.cmd == "sheet":
            cat = json.loads((root / JSON_OUT).read_text())
            n = make_sheet(cat, root, args.out)
            print("wrote %s (%d roles)" % (args.out, n))
            return 0
        if args.check or getattr(args, "check_b", False):
            return 1 if check(root) else 0
        for path, content in targets(root):
            if not path.exists() or path.read_text() != content:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
                print("updated", path.relative_to(root).as_posix())
            else:
                print("up to date", path.relative_to(root).as_posix())
        return 0
    except (CatalogError, ValueError, OSError) as exc:
        print("error:", exc, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
