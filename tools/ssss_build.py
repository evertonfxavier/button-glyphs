#!/usr/bin/env python3
"""Lists the Xbox button textures of Saint Seiya: Soldiers' Soul as plugin "regions".

Usage:  python3 tools/ssss_build.py <game install dir>  >  py_modules/button_glyphs/profiles/saint_seiya_regions.py

The game keeps its UI in resource/ui/<language>/*.emb bundles inside localize.cpk (stored,
not compressed). For every texture the profile redraws, this prints where it lives in the
CPK (offset of its DDS header, size) and the SHA-256 of its original bytes, so the plugin
can refuse any build it does not know. It also checks that the DDS header's reserved
fields (where the plugin keeps its marker) are zero and that every copy of a texture is
laid out like the reference one.
"""
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cpk  # noqa: E402

# (emb file, texture, layout) - every resource/ui/<lang>/<emb> that has it
JOBS = [
    ("command_STEAM.emb", "BTN_PS3_S.dds", "pad", (1024, 1024)),
    ("option_STEAM.emb", "BTN_PS3_S.dds", "pad", (1024, 1024)),
    ("btn_STEAM.emb", "BTN_PS3_S.dds", "pad", (1024, 1024)),
    ("btn_STEAM.emb", "BTN_black.dds", "pad", (1024, 1024)),
    ("battle_STEAM.emb", "cockpit_arts_btn.dds", "cockpit", (1024, 1024)),
    ("continue_STEAM.emb", "btn.dds", "continue", (2048, 1024)),
]
HEADER = 128


def main(game_dir):
    path = os.path.join(game_dir, "localize.cpk")
    out = []
    with open(path, "rb") as f:
        files = cpk.read_toc(f)
        for emb, tex, layout, size in JOBS:
            for key in sorted(files):
                parts = key.split("/")
                if len(parts) != 4 or parts[:2] != ["resource", "ui"] or parts[3] != emb:
                    continue
                off, fsize, extract = files[key]
                if fsize != extract:
                    sys.exit("%s is compressed" % key)
                for name, member, msize in cpk.read_emb(f, off, fsize):
                    if name != tex:
                        continue
                    w, h, mips, fourcc = cpk.read_dds_header(f, member)
                    if (w, h) != size or fourcc != "DXT5" or mips > 1 or msize != HEADER + w * h:
                        sys.exit("%s/%s: unexpected texture %dx%d %s mips=%d" % (key, tex, w, h, fourcc, mips))
                    f.seek(member)
                    data = f.read(msize)
                    if any(data[0x20:0x4C]):
                        sys.exit("%s/%s: reserved header bytes are not zero" % (key, tex))
                    out.append({
                        "key": "%s/%s/%s" % (parts[2], emb[:-4], tex[:-4]),
                        "offset": member, "size": msize, "width": w, "height": h,
                        "sha256": hashlib.sha256(data).hexdigest(), "layout": layout,
                    })
    print('"""Generated by tools/ssss_build.py from the original game files - do not edit.\n')
    print("Saint Seiya: Soldiers' Soul, localize.cpk: every Xbox button texture the profile redraws,")
    print('its position in the archive and the SHA-256 of the original bytes."""\n')
    print("TEXTURES = [")
    for r in out:
        print("    %r," % (r,))
    print("]")
    sys.stderr.write("%d textures; distinct hashes per texture:\n" % len(out))
    seen = {}
    for r in out:
        seen.setdefault((r["key"].split("/", 1)[1], r["sha256"][:12]), []).append(r["key"].split("/")[0])
    for k, v in sorted(seen.items()):
        sys.stderr.write("  %s %s %s\n" % (k[0], k[1], ",".join(v)))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
