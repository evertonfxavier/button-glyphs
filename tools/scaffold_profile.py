def slugify(name):
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "game"


def classname(slug):
    return "".join(part.capitalize() for part in slug.split("_"))


def fill(text, **values):
    for key, value in values.items():
        text = text.replace("@@%s@@" % key, value)
    return text


def scaffold(root, appid, name, kind, slug=None, force=False, dry_run=False):
    """Returns the list of (path, created) and the registry line to add."""
    root = Path(root)
    if kind not in PROFILE:
        raise ValueError("unknown kind %r; use one of: %s" % (kind, ", ".join(PROFILE)))
    if not re.fullmatch(r"\d{1,10}", appid):
        raise ValueError("appid must be a number (Steam app id)")
    slug = slug or slugify(name)
    if not re.fullmatch(r"[a-z][a-z0-9_]*", slug):
        raise ValueError("slug must be lowercase letters, digits and underscores")

    profile_path = root / "py_modules" / "button_glyphs" / "profiles" / ("%s.py" % slug)
    doc_path = root / "docs" / "games" / ("%s-%s.md" % (appid, slug.replace("_", "-")))
    test_path = root / "tests" / ("test_%s.py" % slug)
    template = root / "docs" / "games" / "_template.md"

    doc = template.read_text() if template.exists() else "# @@NAME@@ (@@APPID@@)\n\n## Learnings\n"
    doc = doc.replace("# <Game name> (<appid>)", "# %s (%s)" % (name, appid))
    doc = doc.replace("`profiles/<slug>.py` (class ..., revision 1)",
                      "`profiles/%s.py` (%s, revision 1)" % (slug, kind))

    files = {
        profile_path: fill(PROFILE[kind], NAME=name, APPID=appid),
        doc_path: doc,
        test_path: fill(TEST, NAME=name, APPID=appid, SLUG=slug, CLASS=classname(slug),
                        COMPLETE=COMPLETE[kind]),
    }
    existing = [p for p in files if p.exists()]
    if existing and not force:
        raise FileExistsError("refusing to overwrite: " + ", ".join(str(p.relative_to(root)) for p in existing))

    result = []
    for path, content in files.items():
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        result.append((path, not dry_run))
    registry = ("from .%s import PROFILE as %s" % (slug, slug.upper()), slug.upper())
    return result, registry


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--appid", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--kind", required=True, choices=sorted(PROFILE))
    ap.add_argument("--slug")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--root", default=str(Path(__file__).resolve().parents[1]))
    args = ap.parse_args(argv)
    try:
        files, (import_line, const) = scaffold(args.root, args.appid, args.name, args.kind, args.slug,
                                               args.force, args.dry_run)
    except (ValueError, FileExistsError) as exc:
        print("error:", exc, file=sys.stderr)
        return 2
    verb = "would create" if args.dry_run else "created"
    for path, _ in files:
        print("%s %s" % (verb, Path(path).relative_to(args.root)))
    print("\nNext: fill every TODO with REAL data (never guess), then register in "
          "py_modules/button_glyphs/profiles/__init__.py:\n  %s\n  PROFILES = {..., %s}" % (import_line, const))
    print("Then: /verify-profile %s, docs/games page, tools/learn.py for what you learned." % args.appid)
    return 0


if __name__ == "__main__":
    sys.exit(main())
