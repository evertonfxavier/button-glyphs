// Renders assets/svg/<set>/*.svg to 128 px PNGs for the backend and writes
// src/generated/glyphs.ts (data URIs of the icons the UI previews).
// Usage: pnpm run glyphs
import { Resvg } from "@resvg/resvg-js";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "fs";
import { join } from "path";

const ROOT = new URL("..", import.meta.url).pathname;
const SRC = join(ROOT, "assets/svg");
const OUT = join(ROOT, "py_modules/button_glyphs/glyphs");
const SIZE = 128;

// Icons shown in the panel preview, per style, in role order: head, weapon, empty, legs.
const PREVIEW = {
  ps: ["outline-green-triangle", "outline-purple-square", "outline-red-circle", "outline-blue-cross"],
  xbox: ["y-filled-yellow", "x-filled-blue", "b-filled-red", "a-filled-green"],
};

let count = 0;
for (const set of readdirSync(SRC)) {
  mkdirSync(join(OUT, set), { recursive: true });
  for (const file of readdirSync(join(SRC, set)).filter((f) => f.endsWith(".svg"))) {
    const svg = readFileSync(join(SRC, set, file), "utf8");
    const png = new Resvg(svg, {
      fitTo: { mode: "width", value: SIZE },
      background: "rgba(0,0,0,0)",
    }).render().asPng();
    writeFileSync(join(OUT, set, file.replace(/\.svg$/, ".png")), png);
    count++;
  }
}

const lines = [
  "// Generated by scripts/render-glyphs.mjs - do not edit.",
  "export const GLYPH_PREVIEW: Record<string, string[]> = {",
];
for (const [style, names] of Object.entries(PREVIEW)) {
  const uris = names.map((n) => {
    const svg = readFileSync(join(SRC, style, `${n}.svg`));
    return `    "data:image/svg+xml;base64,${svg.toString("base64")}",`;
  });
  lines.push(`  ${style}: [`, ...uris, "  ],");
}
lines.push("};", "");
mkdirSync(join(ROOT, "src/generated"), { recursive: true });
writeFileSync(join(ROOT, "src/generated/glyphs.ts"), lines.join("\n"));
console.log(`rendered ${count} glyphs to ${OUT}`);
